#!/usr/bin/env python3
"""Build the small, synchronous theme registry; content stays outside theme packages."""
from __future__ import annotations
import json
from pathlib import Path


def default_theme_id(root: Path) -> str:
    path = root / "themes/registry.json"
    return json.loads(path.read_text(encoding="utf-8"))["default"] if path.exists() else "weave"


def load_registry(root: Path) -> dict:
    source = json.loads((root / "themes/registry.json").read_text(encoding="utf-8"))
    themes = []
    for name in source["packages"]:
        if not isinstance(name, str) or not name.replace("-", "").isalnum():
            raise ValueError(f"Invalid theme package id: {name!r}")
        package = json.loads((root / "themes" / name / "theme.json").read_text(encoding="utf-8"))
        if package["id"] != name or package["contractVersion"] != source["contractVersion"]:
            raise ValueError(f"Incompatible theme contract: {name}")
        for key in ("stylesheet", "scene"):
            value = package.get(key)
            if not value:
                continue
            path = (root / value).resolve()
            if not path.is_relative_to((root / "themes").resolve()) or not path.is_file():
                raise ValueError(f"Invalid {key} in theme {name}: {value}")
        themes.append(package)
    ids = {theme["id"] for theme in themes}
    if len(ids) != len(themes) or source["default"] not in ids:
        raise ValueError("Theme ids must be unique and include the default")
    if any(theme.get("fallbackTheme") not in ids for theme in themes):
        raise ValueError("Unknown theme fallback")
    return {"contractVersion": source["contractVersion"], "default": source["default"], "themes": themes}


def build(root: Path) -> dict:
    registry = load_registry(root)
    prefix = "// Generated by scripts/build_themes.py; edit registry.json and package theme.json files.\n"
    (root / "themes/registry.js").write_text(
        prefix + "window.ZQR_THEMES = " + json.dumps(registry, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8")
    image_sources = {}
    manifest_path = root / "resources/pics/derivatives/manifest.json"
    if manifest_path.exists():
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        for name, asset in manifest.get("assets", {}).items():
            variants = sorted((v for v in asset.get("variants", []) if v.get("format") == "webp"),
                              key=lambda v: v["width"])
            if variants:
                image_sources["/" + name.lstrip("/")] = "/" + variants[0]["path"].lstrip("/")
    (root / "includes/js/image-sources.js").write_text(
        "// Generated responsive sources for document previews.\nwindow.ZQR_IMAGE_SOURCES = " +
        json.dumps(image_sources, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
    return registry


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    result = build(root)
    print("Built theme packages: " + ", ".join(theme["id"] for theme in result["themes"]))
