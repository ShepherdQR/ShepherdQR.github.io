// Real-browser regressions for the atlas; uses the repository's existing Playwright runtime.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.BASE_URL || 'http://127.0.0.1:8000';
const out = path.resolve(__dirname,'../output/playwright/knowledge-atlas');
const checks=[];
const check=(name,result)=>{assert(result,name);checks.push(name);};
(async()=>{
    fs.mkdirSync(out,{recursive:true});
    const browser=await chromium.launch({channel:'msedge',headless:true});
    const context=await browser.newContext({viewport:{width:1440,height:1100}});
    const page=await context.newPage();
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    const go=async route=>{await page.goto(base+route);await page.evaluate(()=>window.ZQRTheme.ready);};
    await go('/');
    await page.waitForSelector('#knowledge-interactive:not([hidden])');
    const payload=await page.evaluate(()=>window.KNOWLEDGE_ATLAS);
    check('independent inventories fully represented',payload.counts.standardEntries===306);
    check('all current notes classified',payload.unassigned.length===0&&payload.counts.articles===Object.keys(payload.items).length);
    const subjects = page.locator('#knowledge-view .subject-link');
    const linkedSubjects = await subjects.evaluateAll(links => links.map(link => ({
        id: new URL(link.href).searchParams.get('domain'),
        family: link.closest('.subject-family').dataset.family
    })));
    const expectedSubjects = payload.domains.map(({id, family}) => ({id, family}));
    assert.deepEqual(linkedSubjects.sort((a,b) => a.id.localeCompare(b.id)), expectedSubjects.sort((a,b) => a.id.localeCompare(b.id)));
    checks.push('every printed subject opens the corresponding domain in its family');
    await page.locator('.cover-primary').click();
    check('cover opens the subject index',new URL(page.url()).hash === '#knowledge-map');
    await subjects.first().click();
    await page.goBack();
    check('back restores one complete subject index',await subjects.count() === payload.counts.domains && await page.locator('.knowledge-directory').count() === 1);
    await go('/');
    await page.screenshot({path:path.join(out,'map-desktop.png'),fullPage:false,animations:'disabled'});
    await go('/?domain=literature&branch=literature.poetry#knowledge-map');
    check('deep branch link works',await page.locator('#knowledge-interactive').getAttribute('data-knowledge-node')==='literature.poetry');
    const firstNote = page.locator('.knowledge-note h4 a').first();
    const articlePath = await firstNote.getAttribute('href');
    await firstNote.click();
    check('a note title opens its published article',new URL(page.url()).pathname === articlePath && await page.locator('#markdown-content').isVisible());
    await page.goBack();
    check('back from the article restores its atlas branch',await page.locator('#knowledge-interactive').getAttribute('data-knowledge-node') === 'literature.poetry');
    const firstCount=await page.locator('.knowledge-note').count();
    await page.locator('[data-knowledge-more]').click();
    check('show more reveals additional actual notes',await page.locator('.knowledge-note').count()>firstCount);
    await page.locator('[data-knowledge-type="Thoughts"]').click();
    check('type filter has only thoughts',await page.locator('.knowledge-note h4 a').evaluateAll(a=>a.length>0&&a.every(x=>x.getAttribute('href').startsWith('/thoughts/'))));
    const thoughtCount=Object.values(payload.items).filter(i=>i.type==='Thoughts'&&i.nodes.includes('literature.poetry')).length;
    check('accessible count follows type filter',await page.locator('#knowledge-status').innerText().then(t=>t.includes(thoughtCount+' 篇')));
    await page.evaluate(()=>window.ZQRTheme.setTheme('tomography'));
    check('theme change preserves branch and filter',page.url().includes('kind=Thoughts')&&await page.locator('[data-knowledge-type="Thoughts"]').getAttribute('aria-pressed')==='true');
    await page.screenshot({path:path.join(out,'poetry-tomography.png'),animations:'disabled'});
    await page.locator('#knowledge-search').fill('小说');await page.locator('#knowledge-search-form button').click();
    check('branch search does not leak sibling fields',await page.locator('#knowledge-view .knowledge-tile').count()===0);
    await go('/?domain=agriculture&branch=agriculture.veterinary#knowledge-map');
    check('empty field is honest',await page.locator('.knowledge-empty').innerText().then(t=>t.includes('等待第一篇笔记')));
    check('empty field keeps neighbouring exploration',await page.locator('.knowledge-neighbours a').count()>=2);
    await go('/');
    await page.locator('#knowledge-search').fill('金匮');
    await page.locator('#knowledge-search-form button').click();
    check('search finds actual medicine reading',await page.locator('#knowledge-view a[href="/books/0156/"]').count()===1);
    await page.reload();
    check('search survives reload',await page.locator('#knowledge-search').inputValue()==='金匮');
    await page.locator('#knowledge-search').fill('不存在的搜索词<svg onload=alert(1)>');
    await page.locator('#knowledge-search-form button').click();
    check('unknown search is empty and escaped',await page.locator('.knowledge-empty').count()===1&&await page.locator('#knowledge-view svg').count()===0);
    await go('/?domain=missing&branch=missing.child');
    check('invalid deep link recovers with explanation',await page.locator('#knowledge-view .knowledge-tile').count()===30&&await page.locator('#knowledge-view').innerText().then(t=>t.includes('链接暂未找到')));
    for(const width of [320,390,768,1024,1440]){
        await page.setViewportSize({width,height:900});await go('/');
        check('map fits '+width,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
        await page.locator('#knowledge-view [data-knowledge-node="literature"]').click();
        check('domain fits '+width,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
        await page.screenshot({path:path.join(out,'domain-'+width+'.png'),animations:'disabled'});
    }
    await page.setViewportSize({width:390,height:844});await go('/');
    await page.screenshot({path:path.join(out,'map-mobile.png'),animations:'disabled'});
    const lastGroup = page.locator('.subject-shortcuts a').last();
    const groupAnchor = await lastGroup.getAttribute('href');
    await lastGroup.click();
    check('mobile group shortcut focuses its printed heading',await page.locator(groupAnchor).evaluate(heading => heading === document.activeElement));
    await page.keyboard.press('Tab');
    check('the next Tab focuses a subject in that group',await page.evaluate(() => document.activeElement.matches('.subject-link') && document.activeElement.closest('.subject-family').querySelector('h3').id === location.hash.slice(1)));
    const degraded=await browser.newContext();
    await degraded.route('**/knowledge-atlas-data.js',r=>r.abort());
    const fallback=await degraded.newPage();await fallback.goto(base+'/');
    check('data failure preserves static map',await fallback.locator('#knowledge-static').isVisible()&&await fallback.locator('.knowledge-static-domain').count()===30);
    check('unhydrated subject links target their printed entries',await fallback.locator('#knowledge-static .subject-link').evaluateAll(links =>
        links.length > 0 && links.every(link => document.getElementById(link.hash.slice(1))?.matches('details.knowledge-static-domain'))));
    await degraded.close();
    const futureContext=await browser.newContext();
    const future=structuredClone(payload);
    const analysis=future.domains.find(d=>d.id==='math').children.find(n=>n.id==='math.analysis');
    analysis.children=[{id:'math.analysis.new-question',title:'新的问题',itemKeys:[],children:[{id:'math.analysis.new-question.detail',title:'进一步细分',itemKeys:[]}]}];
    future.redirects={'old-analysis':'math.analysis'};
    await futureContext.route('**/knowledge-atlas-data.js',r=>r.fulfill({contentType:'application/javascript',body:'window.KNOWLEDGE_ATLAS='+JSON.stringify(future)+';'}));
    const futurePage=await futureContext.newPage();
    await futurePage.goto(base+'/?domain=old-analysis');
    check('retired IDs remain navigable',await futurePage.locator('#knowledge-interactive').getAttribute('data-knowledge-node')==='math.analysis');
    await futurePage.locator('.knowledge-tile[data-knowledge-node="math.analysis.new-question"]').click();
    await futurePage.locator('.knowledge-tile[data-knowledge-node="math.analysis.new-question.detail"]').click();
    check('future fields can grow beyond two levels',await futurePage.locator('#knowledge-breadcrumbs').innerText().then(t=>t.includes('新的问题')&&t.includes('进一步细分')));
    await futurePage.reload();
    check('future nested links survive reload',await futurePage.locator('#knowledge-interactive').getAttribute('data-knowledge-node')==='math.analysis.new-question.detail');
    await futureContext.close();
    check('no browser errors',errors.length===0);
    fs.writeFileSync(path.join(out,'checks.json'),JSON.stringify({checks:checks.length,results:checks,errors},null,2));
    console.log('Knowledge browser checks passed: '+checks.length);
    await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
